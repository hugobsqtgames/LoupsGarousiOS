export interface RoleDefinition {
  id: RoleId;
  name: string;
  team: Team;
  expansion: Expansion;
  icon: IconName;
  summary: string;
  power: string;
  activation: string;
  timing: string;
  uses: string;
  targets: string;
  effectDuration: string;
  onDeath: string;
  restrictions: string[];
  interactions: string[];
  /** Ordre d'appel la nuit (null si le rôle ne se réveille pas). */
  nightOrder: number | null;
  nightStep: StepKind | null;
  sources: string[];
  certainty: Certainty;
  uncertainties: string[];
  /** Nombre maximal d'exemplaires dans une composition. */
  maxCopies: number;
  /** Nombre exact requis lorsqu'il est présent (Deux sœurs, Trois frères). */
  exactCopies?: number;
  /** Poids heuristique d'équilibrage (positif = favorise le village). */
  balance: number;
  /** Rôle connu publiquement (Villageois-villageois). */
  public?: boolean;
}

